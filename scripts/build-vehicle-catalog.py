"""Generate the offline, repeatable VehiclesDB seed from a pinned CSV snapshot."""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "go-backend"
DATA = ROOT / "data" / "vehiclesdb"


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def build():
    source = DATA / "vehicles.csv"
    manifest = json.loads((DATA / "manifest.json").read_text(encoding="utf-8"))
    rows = list(csv.DictReader(source.open(encoding="utf-8", newline="")))
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    statements = ["-- Generated by scripts/build-vehicle-catalog.py; do not edit.\nBEGIN;\n"]
    for offset in range(0, len(rows), 500):
        values = []
        for row in rows[offset:offset + 500]:
            identity = "/".join(row[k] for k in ("kind", "make_slug", "model_slug"))
            values.append("(" + ",".join(quote(v) for v in (
                identity, row["kind"], row["make_slug"], row["make_name"],
                row["model_slug"], row["model_name"], row["aliases"], row["former_ids"],
            )) + ")")
        statements.append("INSERT INTO vehicle_catalog (id,kind,make_slug,make_name,model_slug,model_name,aliases,former_ids) VALUES\n" + ",\n".join(values) + "\nON CONFLICT (id) DO NOTHING;\n")
    statements.append("INSERT INTO vehicle_catalog_imports (version,sha256,model_count) VALUES (" +
                      quote(manifest["version"]) + "," + quote(digest) + "," + str(len(rows)) +
                      ") ON CONFLICT (version) DO NOTHING;\nCOMMIT;\n")
    seed = "".join(statements)
    (ROOT / "migrations" / "00028_vehicle_catalog_seed.up.sql").write_text(seed, encoding="utf-8")
    (DATA / "seed.sql").write_text(seed, encoding="utf-8")
    (DATA / "SHA256SUMS").write_text(digest + "  vehicles.csv\n", encoding="utf-8")
    print(f"Generated {len(rows)} models from VehiclesDB {manifest['version']}; sha256={digest}")


if __name__ == "__main__":
    build()
